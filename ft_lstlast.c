#include "libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	t_list	*last_node;

	if (!lst)
		return (NULL);
	last_node = lst;
	while (last_node)
	{
		if (last_node->next == NULL)
			break ;
		last_node = last_node->next;
	}
	return (last_node);
}
