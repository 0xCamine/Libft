#include "libft.h"

// 123 / 10

//   123
// 12
// 1

void	ft_putnbr_fd(int n, int fd)
{
	char	nb;

	nb = 0;
	if (n == -2147483648)
	{
		write(fd, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		n = n * (-1);
		write(fd, "-", 1);
	}
	if (n >= 10)
		ft_putnbr_fd(n / 10, fd);
	nb = (n % 10) + 48;
	write(fd, &nb, 1);
	return ;
}
